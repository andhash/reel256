"""test-vectors/reel256.json -> tests/vectors.h, for the C tests.

    python3 tests/gen_header.py test-vectors/reel256.json > tests/vectors.h
"""

import json
import sys

data = json.load(open(sys.argv[1]))
print(f"/* Generated by tests/gen_header.py from {sys.argv[1]}. */")
print("static const struct { const char *name, *key, *nonce, *ad, *msg, *ct, *tag; } vectors[] = {")
for v in data["vectors"]:
    vals = ", ".join(f'"{v[k]}"' for k in ("key", "nonce", "ad", "msg", "ct", "tag"))
    print(f'    {{"{v["name"]}", {vals}}},')
print("};")
